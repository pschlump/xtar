// Package charset decodes member names stored in legacy single-byte
// character sets — the zips old Windows and classic-Mac tools wrote,
// tar/cpio archives with no declared charset — into UTF-8.  It is the
// engine behind --encoding (unzip -O).
package charset

import "fmt"

// Decoder converts name bytes in one character set to a UTF-8 string.
type Decoder func([]byte) string

// ByName returns the decoder for a character-set name, accepting the
// spellings the native tools' help text uses.
func ByName(name string) (Decoder, error) {
	switch name {
	case "utf-8", "utf8", "UTF-8", "UTF8":
		return func(b []byte) string { return string(b) }, nil
	case "cp437", "CP437", "437", "ibm437", "IBM437":
		return decodeCP437, nil
	case "iso-8859-1", "iso8859-1", "latin1", "latin-1", "ISO-8859-1", "8859-1":
		return func(b []byte) string {
			runes := make([]rune, len(b))
			for i, c := range b {
				runes[i] = rune(c) // Latin-1 maps bytes 0x00-0xFF straight to U+0000-U+00FF
			}
			return string(runes)
		}, nil
	case "mac-roman", "macroman", "MacRoman", "roman", "mac":
		return decodeMacRoman, nil
	}
	return nil, fmt.Errorf("unknown character set %q (want utf-8, cp437, iso-8859-1, or mac-roman)", name)
}

func decodeCP437(b []byte) string {
	needs := false
	for _, c := range b {
		if c >= 0x80 {
			needs = true
			break
		}
	}
	if !needs {
		return string(b)
	}
	runes := make([]rune, len(b))
	for i, c := range b {
		if c < 0x80 {
			runes[i] = rune(c)
		} else {
			runes[i] = cp437Hi[c-0x80]
		}
	}
	return string(runes)
}

